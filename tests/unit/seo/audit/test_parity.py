"""The ported parsers answer exactly as OpenSEO's TypeScript does on the same inputs.

openseo_golden.json holds outputs of upstream d7ea785 page-analyzer.ts and url-utils.ts
(htmlparser2 10.1.0) and robots-parser 3.0.1, generated by running that code.
"""

import json
from pathlib import Path
from typing import Any

import pytest

from octop.infra.seo.audit.analyzer import (
    MAX_EXTRACTED_IMAGES,
    MAX_EXTRACTED_LINKS,
    PageAnalysis,
    analyze_html,
)
from octop.infra.seo.audit.net import USER_AGENT
from octop.infra.seo.audit.robots import parse_robots
from octop.infra.seo.audit.urls import is_same_origin, normalize_url

GOLDEN = json.loads((Path(__file__).parent / "openseo_golden.json").read_text(encoding="utf-8"))
# Fetch fields the analyzer does not produce.
_FETCH_FIELDS = {"url", "statusCode", "redirectUrl", "responseTimeMs"}


def _upstream_shape(analysis: PageAnalysis) -> dict[str, Any]:
    return {
        "title": analysis.title,
        "metaDescription": analysis.meta_description,
        "canonical": analysis.canonical,
        "robotsMeta": analysis.robots_meta,
        "ogTitle": analysis.og_title,
        "ogDescription": analysis.og_description,
        "ogImage": analysis.og_image,
        "h1s": analysis.h1s,
        "headingOrder": analysis.heading_order,
        "wordCount": analysis.word_count,
        "javascriptShell": analysis.javascript_shell,
        "images": analysis.images,
        "links": [
            {
                "targetUrl": link.target_url,
                "anchor": link.anchor,
                "isInternal": link.is_internal,
                "isNofollow": link.is_nofollow,
            }
            for link in analysis.links
        ],
        "hasStructuredData": analysis.has_structured_data,
        "hreflangTags": analysis.hreflang_tags,
    }


@pytest.mark.parametrize("case", GOLDEN["analyzer"], ids=lambda case: case["name"])
def test_analyzer_matches_upstream(case: dict[str, Any]) -> None:
    expected = {k: v for k, v in case["expected"].items() if k not in _FETCH_FIELDS}
    assert _upstream_shape(analyze_html(case["html"], case["page_url"])) == expected


@pytest.mark.parametrize("case", GOLDEN["normalize_url"], ids=lambda case: case["url"])
def test_normalize_url_matches_upstream(case: dict[str, Any]) -> None:
    assert normalize_url(case["url"], case["base"]) == case["expected"]


@pytest.mark.parametrize("case", GOLDEN["same_origin"], ids=lambda case: case["url"])
def test_same_origin_matches_upstream(case: dict[str, Any]) -> None:
    assert is_same_origin(case["url"], case["origin"]) is case["expected"]


@pytest.mark.parametrize("case", GOLDEN["robots"], ids=lambda case: case["text"][:40])
def test_robots_matches_upstream(case: dict[str, Any]) -> None:
    robots = parse_robots("https://example.com", case["text"])
    assert robots.sitemaps == case["sitemaps"]
    for url, allowed in case["allowed"]:
        assert robots.is_allowed(url, USER_AGENT) is allowed, url


def test_extraction_is_capped() -> None:
    links = "".join(f'<a href="/p{i}">p{i}</a>' for i in range(1100))
    images = "".join(f'<img src="/i{i}.png">' for i in range(1100))
    analysis = analyze_html(f"<body>{links}{images}</body>", "https://example.com/")
    assert len(analysis.links) == MAX_EXTRACTED_LINKS
    assert len(analysis.images) == MAX_EXTRACTED_IMAGES
